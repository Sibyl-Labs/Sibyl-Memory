"""Deterministic synthetic corpora for the 2.D scale-fix tests (2026-10-22).

Two builders:

* ``build_small(client)`` — a 3,000-row, four-tier store written through the
  public API. Every query token used by the golden test stays under the
  per-token recall cap (df < 200, journal df < 50), so recall depth, true df
  and the no-decode stage 1 must reproduce the 0.9.0 engine's output exactly.
  The frozen 0.9.0 outputs live in ``fixtures/scale_golden_0_9_0.json``
  (generated by ``scripts/gen_scale_golden.py`` against the unmodified 0.9.0
  tree).

* ``build_large(db_path, tenant, n_entities)`` — a >= 20k-entity store written
  with direct SQL in one transaction (the FTS triggers still fire, so the index
  is the real one). Used for recall depth, true df, name weighting and latency.

``normalize(results)`` maps the volatile fields (timestamps, random journal
ids) to stable values so outputs from two separate builds compare byte-for-byte.
"""
from __future__ import annotations

import hashlib
import json
import random
import sqlite3

# A fixed pseudo-word vocabulary: deterministic, pronounceable, never an English
# stopword or a _DF0_FUNCTION entry (all are >= 6 chars and end in a consonant
# cluster no lexicon carries).
_SYL_A = ["bra", "cle", "dro", "fen", "gal", "hor", "jun", "kel", "lom", "mar",
          "nev", "pol", "qua", "ril", "sto", "tav", "vur", "wex", "yol", "zan"]
_SYL_B = ["dak", "fim", "gox", "hul", "jet", "kib", "lun", "mop", "nix", "pev",
          "rog", "sab", "tuk", "vem", "wid", "yak", "zor", "bex", "cud", "dif"]


def vocabulary(n: int = 2000, seed: int = 7) -> list[str]:
    words = []
    for a in _SYL_A:
        for b in _SYL_B:
            for c in _SYL_B:
                words.append(a + b + c[:2])
    rng = random.Random(seed)
    rng.shuffle(words)
    out = list(dict.fromkeys(words))[:n]
    assert len(out) == n
    return out


def _sentence(rng: random.Random, vocab: list[str], k: int) -> str:
    return " ".join(rng.choice(vocab) for _ in range(k))


class _NoCap:
    """Test-only stand-in for the free-tier cap gate: the fixtures are larger
    than the 5 MB free cap by design (the cap is not under test here)."""

    def check(self, *a, **k):
        return None

    def check_total_local(self, *a, **k):
        return None


def lift_cap(c) -> None:
    c._cap_gate = _NoCap()


def build_small(c, seed: int = 11) -> dict:
    """3,000 rows: 1,800 entities, 100 state, 600 reference, 500 journal."""
    rng = random.Random(seed)
    vocab = vocabulary()
    cats = ["person", "company", "project", "ticket"]
    for i in range(1800):
        cat = cats[i % 4]
        body = {"summary": _sentence(rng, vocab, 24)}
        if i % 15 == 0:   # prep/terminal markers, kept under the 200 df cap
            body["status"] = rng.choice(["draft", "approved"])
        c.set_entity(cat, f"{cat}-{i:04d}", body)
    for i in range(100):
        c.set_state(f"state-{i:03d}", {"notes": _sentence(rng, vocab, 30)})
    for i in range(600):
        text = _sentence(rng, vocab, 40)
        if i % 7 == 0:
            text = "draft " + text
        c.set_reference(f"doc/{i:04d}", text, metadata={"title": f"Doc {i}"})
    for i in range(500):
        c.write_event(evaluated=_sentence(rng, vocab, 10),
                      acted=_sentence(rng, vocab, 6),
                      ts=f"2026-01-01T00:{i // 60:02d}:{i % 60:02d}.000Z")
    return {"vocab": vocab}


def golden_queries() -> list[str]:
    vocab = vocabulary()
    rng = random.Random(99)
    qs = []
    for n in (1, 2, 3, 4, 6):
        for _ in range(6):
            qs.append(" ".join(rng.sample(vocab, n)))
    # terminal / prep-gate queries
    for _ in range(4):
        qs.append("final " + " ".join(rng.sample(vocab, 2)))
        qs.append("approved draft " + rng.choice(vocab))
    # abstention: an unsupported content token
    qs.append(vocab[0] + " zzqnonexistentqq")
    # names and categories
    qs += ["0007", "1203", "0042 " + vocab[5]]
    return qs


def normalize(results) -> list:
    out = []
    for h in results:
        h = dict(h)
        h.pop("ts", None)
        if h.get("tier") == "journal":
            h["key"] = "J:" + hashlib.sha256(
                json.dumps(h.get("body"), sort_keys=True).encode()).hexdigest()[:16]
        out.append(h)
    return out


def digest(obj) -> str:
    return hashlib.sha256(
        json.dumps(obj, sort_keys=True, ensure_ascii=False, default=str).encode()
    ).hexdigest()


# ----------------------------------------------------------------------
# Large store (direct SQL, one transaction)
# ----------------------------------------------------------------------
def build_large(db_path, tenant: str, n_entities: int = 20_000,
                n_refs: int = 2_000, seed: int = 5) -> dict:
    """Write a >= 20k-row store directly. Returns the planted facts.

    Plants:
      * ``common``     one token present in ~30% of rows (true df >> 200)
      * ``hub``        ``person/Orla Vantreeze`` whose name is the query, plus 150
                       long bodies that mention "orla vantreeze" many times
      * ``target``     one reference doc carrying 15 distinctive-but-not-rare
                       tokens, each of which also occurs in ~400 other rows, so at
                       K=200 the target falls outside most tokens' top-K
    """
    from sibyl_memory_client import MemoryClient

    c = MemoryClient.local(db_path, tenant_id=tenant)  # creates schema
    c.close() if hasattr(c, "close") else None
    rng = random.Random(seed)
    vocab = vocabulary()
    target_toks = vocab[100:115]
    common = vocab[1999]
    conn = sqlite3.connect(str(db_path))
    conn.execute("BEGIN")
    cats = ["person", "company", "project", "ticket", "product"]

    def body_words(k):
        ws = [rng.choice(vocab[200:1990]) for _ in range(k)]
        if rng.random() < 0.3:
            ws.append(common)
        if rng.random() < 0.05:       # a terminal-state word, for the prep path
            ws.append("approved")
        # each target token lands in ~2% of rows (df ~ 400+ at 22k rows)
        for t in target_toks:
            if rng.random() < 0.02:
                ws.append(t)
        return " ".join(ws)

    for i in range(n_entities):
        cat = cats[i % 5]
        name = f"{cat}-{i:05d}"
        body = json.dumps({"summary": body_words(30)})
        conn.execute(
            "INSERT INTO entities (id, tenant_id, category, name, status, body) "
            "VALUES (?, ?, ?, ?, 'active', ?)",
            (f"e{i}", tenant, cat, name, body))
    # the named hub + 150 long rows that mention the name in their body
    # a ~500-char card (spec section 3: an entity body is a card, not a dump).
    # Measured while writing this fixture: on a store of ~33-word rows a
    # 150-word card is NOT lifted to rank 1 by NAME_WEIGHT=8 (bm25 length
    # normalisation wins at ~4.5x the average row length); <= 120 words is.
    # That residual is what the stage-0 exact-name lookup (2.C) exists for; the
    # weight is not tuned around it (spec 2.D D2).
    conn.execute(
        "INSERT INTO entities (id, tenant_id, category, name, status, body) "
        "VALUES ('hub', ?, 'person', 'Orla Vantreeze', 'active', ?)",
        (tenant, json.dumps({"role": "account lead", "summary": body_words(60)})))
    for j in range(150):
        body = json.dumps({"text": "orla vantreeze " * 3 + body_words(40)})
        conn.execute(
            "INSERT INTO entities (id, tenant_id, category, name, status, body) "
            "VALUES (?, ?, 'meeting', ?, 'active', ?)",
            (f"m{j}", tenant, f"meeting-{j:03d}", body))
    for i in range(n_refs):
        conn.execute(
            "INSERT INTO reference_documents (tenant_id, doc_key, body, metadata) "
            "VALUES (?, ?, ?, ?)",
            (tenant, f"doc/{i:05d}", body_words(120), json.dumps({"title": f"Doc {i}"})))
    target_body = ("Quarterly target memo " + " ".join(target_toks) + " "
                   + body_words(200))
    conn.execute(
        "INSERT INTO reference_documents (tenant_id, doc_key, body, metadata) "
        "VALUES (?, 'doc/target', ?, ?)",
        (tenant, target_body, json.dumps({"title": "Target"})))
    conn.commit()
    conn.close()
    return {"common": common, "target_tokens": target_toks,
            "hub_name": "Orla Vantreeze", "unsupported": "zzqnonexistentqq"}
